## Why protein helps
Muscle is built and repaired from the amino acids in protein. When total food goes down, protein often goes down with it. Keeping protein steady gives your body what it needs to hold on to muscle, and protein-rich meals tend to keep you full longer.

## How much?
The general baseline for adults is about 0.8 grams per kilogram of body weight a day, but many people do better with more, especially while losing weight or getting older. **Your target depends on you**, so ask your provider for a number and enter it in the Food tab.


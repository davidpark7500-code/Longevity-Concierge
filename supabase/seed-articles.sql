## 1. Sit-to-stand
Sit near the front of a sturdy chair, feet flat and hip-width apart. Lean slightly forward and stand up by pressing through your heels, then sit back down slowly.
- **Easier:** use your hands on your thighs or the armrests.
- **Harder:** slow down the sit, or hold a light weight at your chest.
- Try 2 sets of 8–10.

## 2. Supported push-up
Place your hands on a wall or kitchen counter, a little wider than your shoulders. Step back so your body makes a straight line. Bend your elbows to bring your chest toward the surface, then press away.
- **Easier:** stand closer, or use a wall.
- **Harder:** use a lower surface like a sturdy bench.
- Try 2 sets of 6–10.

## 3. Glute bridge
Lie on your back, knees bent, feet flat. Squeeze your glutes and lift your hips until your body is straight from shoulders to knees. Pause, then lower slowly.
- **Harder:** hold the top for 3 seconds, or lift one foot.
- Try 2 sets of 10.

## How often
General guidelines suggest muscle-strengthening activity at least **two days a week**. Rest a day between sessions when you're starting out, and stop if anything hurts.


## Fiber
The Dietary Guidelines suggest about **14 grams of fiber for every 1,000 calories** you eat, about 22–34 grams a day depending on age and sex. Most people get far less.

Easy ways to add it:
- Add beans or lentils to soups, salads and bowls.
- Pick whole-grain bread, oats or brown rice.
- Keep fruit with the skin on: apples, pears, berries.
- Snack on vegetables, nuts or seeds.
- **Add it slowly.** A sudden jump can cause bloating. Increase over a couple of weeks.

## Fluids
There's no single number for everyone. Needs change with your size, activity and the weather, and food counts too. A simple check: you should rarely feel thirsty, and your urine should be pale yellow.
- Keep a water bottle where you can see it.
- Have a glass with every meal.
- Drink more when you add fiber, exercise or it's hot out.
- If your provider has given you a fluid limit, follow that instead.

